index = []
for stem, slug, name, deva, group, note in BOOKS:
    d = json.loads((HERE / 'build' / 'out' / f'{stem}.json').read_text())
    secs = [{'t': s['title'], 'u': s['units']} for s in d['sections']]
    n = sum(1 for s in secs for u in s['u'] if u.get('kind') != 'note')
    book = {'slug': slug, 'name': name, 'deva': deva, 'note': note, 'intro': d['intro'], 'sections': secs}
    js = f"(window.UPANISHAD_DATA=window.UPANISHAD_DATA||{{}})[{json.dumps(slug)}]={json.dumps(book, ensure_ascii=False, separators=(',', ':'))};\n"
    (DEST / f'{slug}.js').write_text(js)
    index.append({'slug': slug, 'name': name, 'deva': deva, 'group': group, 'note': note, 'verses': n})
    print(f'{slug:16} {n:4} verses {len(js)//1024:5} KB')
(DEST / 'index.js').write_text('// Generated by Documents/upanishads/export.py, do not edit by hand.\nwindow.UPANISHAD_INDEX=' +
                               json.dumps(index, ensure_ascii=False, indent=1) + ';\n')
assert len(index) == len(BOOKS) and all(i['verses'] > 0 for i in index), 'a book produced no verses'
